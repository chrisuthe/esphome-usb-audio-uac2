// A hand-built configuration descriptor of a plain USB Audio Class 1.0 stereo speaker: 16-bit at 44100 and 48000 Hz,
// one adaptive OUT endpoint with the sampling frequency control, mute and volume on the master channel.
// No captured UAC 1.0 device here has a speaker, so this is what the UAC 1.0 playback comparison streams to.
#pragma once

static const uint8_t UAC1_SPEAKER_DESC[] = {
    // Configuration: 113 bytes in total, 2 interfaces, bus powered, 100 mA
    0x09, 0x02, 0x71, 0x00, 0x02, 0x01, 0x00, 0x80, 0x32,
    // Interface 0: AudioControl, no endpoints
    0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x00, 0x00,
    // AudioControl header: bcdADC 1.00, 40 bytes of class-specific descriptors, 1 streaming interface (1)
    0x09, 0x24, 0x01, 0x00, 0x01, 0x28, 0x00, 0x01, 0x01,
    // Input terminal 1: USB streaming (0x0101), 2 channels, left and right front
    0x0C, 0x24, 0x02, 0x01, 0x01, 0x01, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00,
    // Feature unit 2, fed by terminal 1: mute and volume on the master channel, nothing per channel
    0x0A, 0x24, 0x06, 0x02, 0x01, 0x01, 0x03, 0x00, 0x00, 0x00,
    // Output terminal 3: speaker (0x0301), fed by unit 2
    0x09, 0x24, 0x03, 0x03, 0x01, 0x03, 0x00, 0x02, 0x00,
    // Interface 1 alternate 0: AudioStreaming, no endpoints (the stream is off)
    0x09, 0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x00, 0x00,
    // Interface 1 alternate 1: AudioStreaming, 1 endpoint
    0x09, 0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x00, 0x00,
    // AudioStreaming general: connected to terminal 1, 1 frame of delay, PCM
    0x07, 0x24, 0x01, 0x01, 0x01, 0x01, 0x00,
    // Format type I: 2 channels, 2 bytes per sample, 16 bits, 2 sample rates: 44100 and 48000 Hz
    0x0E, 0x24, 0x02, 0x01, 0x02, 0x02, 0x10, 0x02, 0x44, 0xAC, 0x00, 0x80, 0xBB, 0x00,
    // Endpoint 1 OUT: isochronous adaptive, 200 bytes at most, every frame
    0x09, 0x05, 0x01, 0x09, 0xC8, 0x00, 0x01, 0x00, 0x00,
    // Class-specific endpoint: sampling frequency control
    0x07, 0x25, 0x01, 0x01, 0x00, 0x00, 0x00,
};
